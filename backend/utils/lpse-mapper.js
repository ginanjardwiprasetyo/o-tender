/**
 * Get SPSE slug from LPSE code and/or name.
 * Priority: hardcoded mapping → heuristic from name → 'nasional'
 */
function getSlug(kd_lpse, name = '') {
    const codeStr = String(kd_lpse);
    if (mapping[codeStr]) return mapping[codeStr];

    if (!name) return 'nasional';

    // Heuristic: strip common prefixes, normalize
    const nameLower = name.toLowerCase();
    let slug = nameLower
        .replace(/^lpse\s+/i, '')
        .replace(/^kabupaten\s+/i, '')
        .replace(/^kota\s+/i, '')
        .replace(/^provinsi\s+/i, '')
        .replace(/^daerah istimewa\s+/i, '')
        .replace(/[^a-z0-9]/g, '')
        .trim();

    // Append suffix based on original name
    if (nameLower.includes('kabupaten')) slug += 'kab';
    else if (nameLower.includes('kota')) slug += 'kota';
    else if (nameLower.includes('provinsi') || nameLower.includes('prov')) slug += 'prov';

    // Yogyakarta special case
    slug = slug.replace('yogyakarta', 'jogja');

    return slug || 'nasional';
}

/**
 * Get the base URL for a given LPSE slug.
 * All LPSEs are now accessed via the central portal: spse.inaproc.id/slug
 */
function getBaseUrl(slug) {
    return `https://spse.inaproc.id/${slug}`;
}

