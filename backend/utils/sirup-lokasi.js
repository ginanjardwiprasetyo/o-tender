// Reverse map: lokasi ID → province
const LOKASI_TO_PROVINCE = {};
for (const [prov, ids] of Object.entries(PROVINCE_LOKASI)) {
    for (const id of ids) {
        LOKASI_TO_PROVINCE[id] = prov;
    }
}

const ALL_PROVINCES = Object.keys(PROVINCE_LOKASI).sort();

function resolveProvinceIds(provinces) {
    const ids = [];
    for (const prov of provinces) {
        const provIds = PROVINCE_LOKASI[prov];
        if (provIds) ids.push(...provIds);
    }
    return [...new Set(ids)];
}

function getProvince(lokasiId) {
    return LOKASI_TO_PROVINCE[lokasiId] || null;
}

function getProvincesWithCounts() {
    return ALL_PROVINCES.map(name => ({
        name,
        count: PROVINCE_LOKASI[name].length
    }));
}

